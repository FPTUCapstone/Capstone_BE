-- UC-15 demo data: adds ONE fresh rerouting proposal (a "drop the middle stop" severe-weather alternative) to an
-- EXISTING open navigation session, so the Re-routing Suggestion screen can be reviewed without waiting for the scan job.
--
-- STATUS: written offline and cross-checked against the schema files only. It has NOT been executed anywhere.
-- Run it first on Azure UAT as a dry run (set @DryRun = 1: the whole script runs in one transaction and ends with
-- ROLLBACK), read the PRINT output, and only then run it again with @DryRun = 0. Never run it on a local database.
--
-- Usage: set @SessionId to a Navigating/Exploring session whose itinerary was generated by the planner (it has a
-- scheduling request) and that still has at least two Pending stops. A proposal stays answerable for 15 minutes
-- (Rerouting:ProposalTtl), so run the script right before the demo; running it again after the previous proposal was
-- answered or has expired creates a new one. Safe to rerun: it does nothing while a proposal for the session is still open.
-- No itinerary, session item or navigation state is touched: only an Incident, its Notification and a ReroutingEvent are added.
SET ANSI_NULLS ON;
SET ANSI_PADDING ON;
SET ANSI_WARNINGS ON;
SET ARITHABORT ON;
SET CONCAT_NULL_YIELDS_NULL ON;
SET QUOTED_IDENTIFIER ON;
SET NUMERIC_ROUNDABORT OFF;
SET XACT_ABORT ON;

DECLARE @SessionId BIGINT = NULL;   -- REQUIRED: the trip.TripSessions.session_id to demo on
DECLARE @DryRun BIT = 1;            -- 1 = roll everything back at the end

IF @SessionId IS NULL
    THROW 51500, 'Set @SessionId to the navigation session to attach the demo proposal to.', 1;

BEGIN TRANSACTION;

DECLARE @now DATETIME2 = SYSUTCDATETIME();
DECLARE @traveler BIGINT, @itineraryId BIGINT, @fsmState VARCHAR(12), @endedAt DATETIME2, @expiresAt DATETIME2;
SELECT @traveler = traveler_user_id, @itineraryId = itinerary_id, @fsmState = fsm_state, @endedAt = ended_at, @expiresAt = expires_at
FROM trip.TripSessions WHERE session_id = @SessionId;

IF @traveler IS NULL
    THROW 51501, 'The session does not exist.', 1;
IF @endedAt IS NOT NULL OR @fsmState NOT IN ('Navigating', 'Exploring') OR (@expiresAt IS NOT NULL AND @expiresAt <= @now)
    THROW 51502, 'The session is not open (Navigating or Exploring and not expired).', 1;
IF NOT EXISTS (
    SELECT 1 FROM planning.Itineraries itinerary
    WHERE itinerary.itinerary_id = @itineraryId AND itinerary.scheduling_request_id IS NOT NULL)
    THROW 51503, 'The itinerary has no scheduling request, so the Rerouting Engine would never propose for it.', 1;

-- At most one open proposal per session (the same rule the Rerouting Engine applies).
IF EXISTS (
    SELECT 1 FROM trip.ReroutingEvents
    WHERE session_id = @SessionId AND status = 'Proposed' AND proposed_at >= DATEADD(MINUTE, -15, @now))
BEGIN
    PRINT 'A proposal for this session is still open; nothing was added.';
    ROLLBACK TRANSACTION;
    RETURN;
END;

-- Pending stops in order; the second one is the stop the alert is about and the one the proposal drops.
DECLARE @pending TABLE (
    position INT NOT NULL,
    itinerary_item_id BIGINT NOT NULL,
    poi_id BIGINT NOT NULL,
    poi_name NVARCHAR(200) NOT NULL,
    latitude DECIMAL(9,6) NOT NULL,
    longitude DECIMAL(9,6) NOT NULL,
    planned_arrival DATETIME2 NOT NULL,
    planned_departure DATETIME2 NOT NULL,
    is_mandatory BIT NOT NULL);
INSERT @pending(position, itinerary_item_id, poi_id, poi_name, latitude, longitude, planned_arrival, planned_departure, is_mandatory)
SELECT ROW_NUMBER() OVER (ORDER BY sequence_no), itinerary_item_id, poi_id, poi_name, latitude, longitude,
       planned_arrival, planned_departure, is_mandatory
FROM trip.TripSessionItems
WHERE session_id = @SessionId AND reached_at IS NULL AND skipped_at IS NULL;

IF (SELECT COUNT(*) FROM @pending) < 2
    THROW 51504, 'The session needs at least two Pending stops for the demo proposal.', 1;

DECLARE @affectedItem BIGINT, @affectedPoi BIGINT, @affectedName NVARCHAR(200);
SELECT @affectedItem = itinerary_item_id, @affectedPoi = poi_id, @affectedName = poi_name FROM @pending WHERE position = 2;
IF (SELECT is_mandatory FROM @pending WHERE position = 2) = 1
    THROW 51505, 'The second Pending stop is mandatory; the engine never drops a mandatory stop. Pick another session.', 1;

-- 1. The alert (the same shape the scan job creates) and its notification (marked Sent, no delivery work is queued, so no push is attempted).
DECLARE @incident BIGINT;
INSERT trip.Incidents(session_id, incident_type, description, affected_itinerary_item_id, source_key, detected_at)
VALUES (@SessionId, 'SevereWeather', N'UC-15 demo: heavy rain forecast at ' + @affectedName,
        @affectedItem, N'uc15-demo:' + CONVERT(NVARCHAR(40), NEWID()), @now);
SET @incident = CONVERT(BIGINT, SCOPE_IDENTITY());
INSERT dbo.Notifications(user_id, channel, type, title, body, related_entity_type, related_entity_id, status, created_at, sent_at)
VALUES (@traveler, 'Push', N'TripAlert', N'TripMate trip alert',
        N'Open TripMate to review an update to your active trip.', N'Incident', @incident, 'Sent', @now, @now);

-- 2. The proposal snapshot, schema version 1 (see ReroutingProposalSnapshot). Instants are ISO 8601 UTC with a Z.
DECLARE @baseStops NVARCHAR(MAX) = (
    SELECT itinerary_item_id AS itineraryItemId, poi_id AS poiId, poi_name AS name, latitude AS latitude, longitude AS longitude,
           CONVERT(VARCHAR(33), planned_arrival, 127) + 'Z' AS plannedArrivalUtc,
           CONVERT(VARCHAR(33), planned_departure, 127) + 'Z' AS plannedDepartureUtc,
           is_mandatory AS isMandatory
    FROM @pending ORDER BY position FOR JSON PATH);
DECLARE @proposedStops NVARCHAR(MAX) = (
    SELECT poi_id AS poiId, poi_name AS name, latitude AS latitude, longitude AS longitude,
           CONVERT(VARCHAR(33), planned_arrival, 127) + 'Z' AS plannedArrivalUtc,
           CONVERT(VARCHAR(33), planned_departure, 127) + 'Z' AS plannedDepartureUtc,
           is_mandatory AS isMandatory, 'Kept' AS change
    FROM @pending WHERE position <> 2 ORDER BY position FOR JSON PATH);

DECLARE @anchorLat DECIMAL(9,6), @anchorLng DECIMAL(9,6), @itineraryVersion INT, @lastArrival DATETIME2, @lastProposedArrival DATETIME2;
SELECT @anchorLat = latitude, @anchorLng = longitude FROM @pending WHERE position = 1;
SELECT @itineraryVersion = version FROM planning.Itineraries WHERE itinerary_id = @itineraryId;
SELECT @lastArrival = planned_arrival FROM @pending WHERE position = (SELECT MAX(position) FROM @pending);
SELECT @lastProposedArrival = planned_arrival FROM @pending WHERE position = (SELECT MAX(position) FROM @pending WHERE position <> 2);

DECLARE @snapshot NVARCHAR(MAX) =
    N'{"schemaVersion":1,"strategy":"Drop","reasonCode":"trip_alert.severe_weather"'
    + N',"baseItineraryId":' + CONVERT(NVARCHAR(20), @itineraryId)
    + N',"baseItineraryVersion":' + CONVERT(NVARCHAR(10), @itineraryVersion)
    + N',"anchor":{"startAtUtc":"' + CONVERT(VARCHAR(33), @now, 127) + N'Z","latitude":' + CONVERT(NVARCHAR(20), @anchorLat)
    + N',"longitude":' + CONVERT(NVARCHAR(20), @anchorLng) + N',"availableMinutes":240}'
    + N',"baseStops":' + @baseStops
    + N',"proposedStops":' + @proposedStops
    + N',"removedPoiIds":[' + CONVERT(NVARCHAR(20), @affectedPoi) + N']'
    + N',"affectedItineraryItemIds":[' + CONVERT(NVARCHAR(20), @affectedItem) + N']'
    + N',"travelTimeDiffMinutes":-10'
    + N',"arrivalTimeDiffMinutes":' + CONVERT(NVARCHAR(10), DATEDIFF(MINUTE, @lastArrival, @lastProposedArrival))
    + N',"endAtUtc":"' + CONVERT(VARCHAR(33), DATEADD(HOUR, 4, @now), 127) + N'Z"}';

IF ISJSON(@snapshot) <> 1
    THROW 51506, 'The generated snapshot is not valid JSON.', 1;

INSERT trip.ReroutingEvents(incident_id, session_id, proposed_itinerary_snapshot, status, proposed_at)
VALUES (@incident, @SessionId, @snapshot, 'Proposed', @now);
DECLARE @proposal BIGINT = CONVERT(BIGINT, SCOPE_IDENTITY());

PRINT CONCAT('Demo proposal ', @proposal, ' created for session ', @SessionId, ' (alert ', @incident, '). It can be answered until ',
             CONVERT(VARCHAR(33), DATEADD(MINUTE, 15, @now), 127), 'Z.');
PRINT CONCAT('GET /api/v1/navigation-sessions/', @SessionId, '/rerouting-proposals/', @proposal);

IF @DryRun = 1
BEGIN
    PRINT 'Dry run: rolling back.';
    ROLLBACK TRANSACTION;
END
ELSE
    COMMIT TRANSACTION;
