using System.Diagnostics;
using System.Globalization;
using System.Runtime;
using System.Text;

using TripMate.Application.UnitTests.Features.Scheduling.Benchmarks.Shadow;
using TripMate.Application.UnitTests.Features.Scheduling.Benchmarks.Weighted;
using TripMate.Application.UnitTests.Features.Scheduling.Fixtures;
using TripMate.Application.UnitTests.Features.Scheduling.Golden;

/// <summary>
/// ADR-002 §8 local load test: concurrent generations over the c10–c40 corpus on a limited CPU set, for the switched mode
/// and the current production mode. Generator only (no HTTP, database or Mapbox), because only the solver changes.
/// </summary>
internal static class LoadTest
{
    public static async Task<string> RunAsync(
        string root,
        IReadOnlyDictionary<string, string?>? overrides,
        IReadOnlyList<int> concurrencies,
        int rounds,
        string runDate)
    {
        var cityData = SchedulingBenchmarkScenarioFactory.CreateDaNangV3bData();
        var work = GoldenScenarioFactory.CreateAllScenarios()
            .Where(scenario => scenario.Id.StartsWith("grid-c", StringComparison.Ordinal))
            .SelectMany(scenario => cityData.Personas.Select(persona => (Scenario: scenario, Persona: persona)))
            .ToArray();

        var text = new StringBuilder();
        var invariant = CultureInfo.InvariantCulture;
        text.AppendLine("# UC-10 WeightedUtility local load test (ADR-002 §8)");
        text.AppendLine();
        text.AppendLine("> Generated by `tools/benchmarks/weighted-gate --load`; do not edit by hand.");
        text.AppendLine();
        text.AppendLine(invariant, $"- Run date: {runDate}; machine: {Environment.GetEnvironmentVariable("PROCESSOR_IDENTIFIER") ?? Environment.MachineName}.");
        text.AppendLine(invariant, $"- CPUs visible to the process: {Environment.ProcessorCount}; server GC: {GCSettings.IsServerGC}.");
        text.AppendLine(invariant, $"- Work: {work.Length} generations per round (c10–c40 corpus × {cityData.Personas.Count} personas), {rounds} rounds, after one sequential warmup round.");
        text.AppendLine("- Each generation is one request: ranking blend, weighted inputs, heuristic, CSP, validation (time limit 2500 ms).");
        text.AppendLine();
        text.AppendLine("| Mode | Concurrency | Requests | Throughput req/s | p50 ms | p95 ms | p99 ms | max ms | p95 c40 ms | Time limit | Failed |");
        text.AppendLine("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|");

        foreach (var mode in new[] { "WeightedUtility", "Lexicographic" })
        {
            var settings = new Dictionary<string, string?>(overrides ?? new Dictionary<string, string?>())
            {
                ["SchedulingGeneration:Csp:Mode"] = mode,
            };
            var configuration = WeightedGateConfiguration.LoadShipped(root, settings);
            foreach (var (scenario, persona) in work)
            {
                _ = await WeightedGateExecutor.RunAsync(scenario, persona, configuration, 0, 1);
            }

            foreach (var concurrency in concurrencies)
            {
                var results = new System.Collections.Concurrent.ConcurrentBag<(int Candidates, double Ms, bool TimeLimit, bool Failed)>();
                var clock = Stopwatch.StartNew();
                await Parallel.ForEachAsync(
                    Enumerable.Range(0, rounds).SelectMany(_ => work),
                    new ParallelOptions { MaxDegreeOfParallelism = concurrency },
                    async (item, cancellationToken) =>
                    {
                        var run = await WeightedGateExecutor.RunAsync(item.Scenario, item.Persona, configuration, 0, 1, cancellationToken);
                        results.Add((run.CandidateCount, run.SamplesMs[0], run.TimeLimitReached, !run.Feasible));
                    });
                clock.Stop();

                var all = results.Select(result => result.Ms).ToArray();
                var c40 = results.Where(result => result.Candidates >= 40).Select(result => result.Ms).ToArray();
                text.AppendLine(invariant, $"| {mode} | {concurrency} | {all.Length} | {all.Length / clock.Elapsed.TotalSeconds:F1} | {SolverComparisonReport.Percentile(all, 0.50):F1} | {SolverComparisonReport.Percentile(all, 0.95):F1} | {SolverComparisonReport.Percentile(all, 0.99):F1} | {all.Max():F1} | {SolverComparisonReport.Percentile(c40, 0.95):F1} | {results.Count(result => result.TimeLimit)} | {results.Count(result => result.Failed)} |");
                Console.WriteLine($"{mode} x{concurrency}: done in {clock.Elapsed.TotalSeconds:F1} s");
            }
        }

        text.AppendLine();
        text.AppendLine("## Limitations");
        text.AppendLine();
        text.AppendLine("- Generator only: HTTP, database, ranking provider and Mapbox latency are not included and do not depend on the mode.");
        text.AppendLine("- Railway vCPUs are shared; this machine's cores may be faster or slower per core.");
        text.AppendLine("- Failed counts infeasible plans, which the corpus contains by design and which are identical across modes.");
        return text.ToString();
    }
}
